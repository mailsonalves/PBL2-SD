# Pássaro Inimigo Invertido (Vermelho)
inimigo_invertido = []
for row in flappy:
    linha_vermelha = [0x15 if p == 0x12 else p for p in row]
    linha_vermelha.reverse()
    inimigo_invertido.append(linha_vermelha)

