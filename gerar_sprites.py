sprites = [flappy, inimigo_invertido, nuvem_branca]

def fatiar_para_8x8(sprite_16x16):
    quadrantes = [(0, 0), (8, 0), (0, 8), (8, 8)]
    blocos = []
    for ox, oy in quadrantes:
        bloco = []
        for y in range(8):
            for x in range(8):
                bloco.append(f"{sprite_16x16[oy + y][ox + x]:02X}")
        blocos.append(bloco)
    return blocos

# 1. ATUALIZAR BACKGROUND_SPRITES.HEX
try:
    with open("tiles.hex", "r") as f:
        lines = [l.strip() for l in f if l.strip()]
except FileNotFoundError:
    lines = ["00"] * 16384

if len(lines) < 16384:
    lines.extend(["00"] * (16384 - len(lines)))

linha_atual = 0x20 * 64
for sprite in sprites:
    for bloco in fatiar_para_8x8(sprite):
        for byte_pixel in bloco:
            lines[linha_atual] = byte_pixel
            linha_atual += 1

with open("background_sprites.hex", "w") as f:
    f.write("\n".join(lines[:16384]) + "\n")


# 2. GERAR O PROGRAM.HEX (ANIMAÇÃO EM LOOP)
def cmd_scroll(x, y):
    val = (5 << 28) | ((x & 0x1FF) << 8) | (y & 0xFF)
    return f"{val:08X}\n"

def cmd_sprite(sprite_id, x, y, tile_id):
    val = (6 << 28) | ((sprite_id & 0x1F) << 23) | ((x & 0x1FF) << 14) | ((y & 0xFF) << 6) | (tile_id & 0x3F)
    return f"{val:08X}\n"

with open("program.hex", "w") as f:
    f.write("0F000000\n") # Clear Screen
    
    # Gerar 160 frames de animação
    for frame in range(160):
        scroll_x = (frame * 1) % 320
        flappy_y = 100 + (frame % 4) # Balanço leve
        
        # Inimigo se move da direita pra esquerda mais rápido que o cenário
        inimigo_x = 320 - ((frame * 3) % 350)
        
        # Duas nuvens em diferentes posições e velocidades
        nuvem1_x = 300 - ((frame * 2) % 350)
        nuvem2_x = 150 - ((frame * 2) % 350)

        f.write(cmd_scroll(scroll_x, 0))
        f.write(cmd_sprite(0, 70, flappy_y, 0x20))       # Flappy (ID=0)
        f.write(cmd_sprite(1, inimigo_x, 40, 0x24))      # Inimigo (ID=1, Y=40 na altura da nuvem)
        f.write(cmd_sprite(2, nuvem1_x, 20, 0x28))       # Nuvem 1 (ID=2)
        f.write(cmd_sprite(3, nuvem2_x, 60, 0x28))       # Nuvem 2 (ID=3)
        
        # Limpar o Slot 4 que continha o cano corrompido
        f.write(cmd_sprite(4, 400, 250, 0x00))           # Joga para fora da tela
        
        f.write("E0000000\n") # Wait VBLANK
    
    f.write("F0000001\n") # Jump para a linha 1 (repetir animação)

